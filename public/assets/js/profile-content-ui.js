export const el = (tag, text = "", className = "") => {
  const node = document.createElement(tag);
  node.textContent = text;
  if (className) node.className = className;
  return node;
};
export function safeLink(url) {
  try {
    const parsed = new URL(url);
    return ["https:", "http:"].includes(parsed.protocol) &&
      !parsed.username &&
      !parsed.password
      ? parsed.href
      : "";
  } catch {
    return "";
  }
}
export function dateText(value) {
  if (!value?.year) return "";
  return (
    [value.year, value.month || null, value.day || null]
      .filter((v) => v !== null)
      .map((v) => Number(v).toLocaleString("fa-IR", { useGrouping: false }))
      .join("/") + (value.calendar === "gregory" ? " میلادی" : " شمسی")
  );
}
export function renderItem(section, item, profileId, sections = {}) {
  const article = el("article", "", "content-item");
  article.id = `item-${item.id}`;
  const url = iconUrl(item, profileId);
  if (url) { const image = el("img", "", "profile-item-icon"); image.src = url; image.alt = ""; image.width = 32; image.height = 32; image.loading = "lazy"; article.append(image); }
  const title = item[titleFields[section]] || "آیتم در حال تکمیل";
  article.append(el("h3", enumLabels[title] || title));
  const summary =
    item.summary || item.description || item.subtitle || item.content || "";
  if (summary) article.append(el("p", summary, "content-summary"));
  const details = el("details");
  details.append(el("summary", "مشاهدهٔ جزئیات"));
  const list = el("dl", "", "content-fields");
  for (const [field, value] of Object.entries(item)) {
    if (
      !labels[field] ||
      [
        "evidence",
        "media",
        "links",
        "verificationStatus",
        "visibility",
      ].includes(field) ||
      field === titleFields[section] ||
      !value ||
      (Array.isArray(value) && !value.length)
    )
      continue;
    if (
      ["summary", "description", "subtitle", "content"].includes(field) &&
      value === summary
    )
      continue;
    let display = "";
    if (Array.isArray(value)) {
      const target = {
        skillIds: "skills",
        projectIds: "projects",
        experienceIds: "experiences",
        certificationIds: "certifications",
      }[field];
      display = value
        .map((v) =>
          target
            ? (sections[target] || []).find((i) => i.id === v)?.[
                titleFields[target]
              ] || sectionLabels[target]
            : v,
        )
        .join("، ");
    } else if (typeof value === "object") display = dateText(value);
    else if (typeof value === "boolean") display = value ? "بله" : "";
    else display = enumLabels[value] || String(value);
    if (!display) continue;
    list.append(el("dt", labels[field]));
    const dd = el("dd");
    dd.dir = "auto";
    const url = field === "url" || field.endsWith("Url") ? safeLink(value) : "";
    if (url) {
      const a = el("a", "مشاهدهٔ منبع");
      a.href = url;
      a.rel = "noopener noreferrer";
      a.target = "_blank";
      dd.append(a);
    } else dd.textContent = display;
    list.append(dd);
  }
  details.append(list);
  if (section === "recommendations")
    details.append(
      el(
        "p",
        "این متن را صاحب پروفایل همراه با منبع ثبت کرده است؛ تأیید نویسنده توسط هاتف انجام نشده است.",
        "hint",
      ),
    );
  for (const reference of [...(item.links || []), ...(item.evidence || [])]) {
    const url = safeLink(reference.url);
    if (!url) continue;
    const a = el("a", reference.title || "مشاهدهٔ منبع", "content-reference");
    a.href = url;
    a.target = "_blank";
    a.rel = "noopener noreferrer";
    details.append(a);
    if (reference.verificationStatus)
      details.append(
        el(
          "small",
          enumLabels[reference.verificationStatus] || "خوداظهاری؛ تأیید نشده",
          "hint",
        ),
      );
  }
  const gallery = el("div", "", "content-gallery");
  for (const media of item.media || []) {
    const img = document.createElement("img");
    img.alt = media.alt || `تصویری از ${title}`;
    img.loading = "lazy";
    img.src = `/api/profiles/${encodeURIComponent(profileId)}/media/${encodeURIComponent(media.id)}`;
    img.onerror = () => img.remove();
    gallery.append(img);
  }
  details.append(gallery);
  article.append(details);
  return article;
}
